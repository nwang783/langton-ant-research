#!/usr/bin/env python3
"""Independent complex-coordinate BFS replay of the position-only k9 record proof.
No source/inventory imports. Feasible words generated by literal branching.
"""
import json
from pathlib import Path
from collections import Counter
A='RRLRRRRLR'
def trace(word,heading=1j,origin=0j):
 p=origin;events=[]
 for c in word:
  events.append((p,c));heading*=(-1j if c=='R'else 1j);p+=heading
 return events,p,heading

def extend(events,previous=None,upper_white=False):
 d={}if previous is None else dict(previous)
 for p,c in events:
  if p in d:
   if d[p]==c:return None
  elif upper_white and p.imag>=0 and c=='L':return None
  d[p]=c
 return d

def words(n):
 level=[('',0j,1j,{})]
 for depth in range(n):
  nxt=[]
  for w,p,h,last in level:
   for c in 'RL':
    new=extend([(p,c)],last)
    if new is not None:
     hh=h*(-1j if c=='R'else 1j);nxt.append((w+c,p+hh,hh,new))
  level=nxt
 return sorted(w for w,p,h,last in level)
W=words(9);inventory=[]
for hc in (1j,1,-1j,-1):
 for c in 'RL':
  target=3*hc*(-1j if c=='R'else 1j)
  for hf in (hc,-hc):
   for w in W:
    ev,end,hh=trace(w,hf)
    if end==target:
     top=max(p.imag for p,c in ev);assert top<=4 and(target.imag==3 or top<=2)
     inventory.append((hc,c,hf,w))
pairs=[]
for hf in(1,-1):
 for u in W:
  ev,p,h=trace(u,hf,-3j)
  if p:continue
  for v in W:
   ev2,end,h2=trace(v,h)
   if end!=3 or extend(ev+ev2,upper_white=True)is None:continue
   assert h==1j and v==A and max(z.imag for z,c in ev)<0
   pairs.append(dict(previous_heading=1 if hf==1 else 3,previous_word=u,record_heading=0,record_word=v))
coarse,ep,eh=trace(A);pts=[z for z,c in coarse]+[ep]
level=[(1j,{})];counts=[1];conflicts=0
for n in range(9):
 nxt=[]
 for h,last in level:
  for w in([A]if n==0 else W):
   ev,p,hh=trace(w,h,3*pts[n])
   if p!=3*pts[n+1]:continue
   new=extend(ev,last)
   if new is None:conflicts+=1
   else:nxt.append((hh,new))
 level=nxt;counts.append(len(level))
assert not level
src=json.loads((Path(__file__).resolve().parents[1]/'causal_reduction/morphic_candidates/position_k9_record_certificate.json').read_text())
assert len(W)==src['internally_legal_words']==262
assert len(inventory)==src['oriented_inventory_count']==240
assert sorted(pairs,key=lambda x:(x['previous_heading'],x['previous_word']))==sorted(src['record_pairs'],key=lambda x:(x['previous_heading'],x['previous_word']))
assert {str(n):c for n,c in enumerate(counts)if c}==src['nodes_by_depth']
assert conflicts==src['chronology_conflicts']==8877
out=dict(status='PASS independent complete finite replay',internally_feasible_words=len(W),oriented_images=len(inventory),record_pairs=pairs,refinement_BFS_levels=counts,nodes=sum(counts),conflicts=conflicts,complete_refinements=len(level))
Path(__file__).with_suffix('.json').write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out,indent=2))
